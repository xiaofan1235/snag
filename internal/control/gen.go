// gen.go —— 从 *states.yaml 生成状态机代码（*_sm.gen.go）与状态图（*_states.md）。
// 用法：go generate ./internal/control/   （或在本目录 go run gen.go）
//
// 一个生成器驱动多台状态机（Run / Job / …，见 machines）。每台机器产物相互独立：
//   - Run 保持历史导出 API（无前缀）：Event / Next / AllEvents / AllStates / IsTerminal；
//   - Job 用 Job 前缀：JobEvent / JobNext / JobAllEvents / JobAllStates / JobIsTerminal。
//
// 生成的 <P>Next(from, event) 对任意 (状态,事件) 都有确定结果：已登记迁移返回 (to, true)，
// 未登记返回 (from, false) —— 显式拒绝、不 panic（§5.1/§5.2 完整迁移表）。
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"go.yaml.in/yaml/v3"
)

// machine 描述一台状态机的输入文件与命名方案。
type machine struct {
	yamlFile string // 输入：states.yaml / job_states.yaml
	goFile   string // 输出：run_sm.gen.go / job_sm.gen.go
	mdFile   string // 输出：run_states.md / job_states.md
	title    string // 文档标题用：Run / Job
	specRef  string // 规范章节：§5.1 / §5.2
	expPfx   string // 导出前缀："" / "Job"
	unexpPfx string // 非导出前缀：run / job（内部 map/struct 命名，避免同包冲突）
	domType  string // domain 状态类型：RunState / JobState
	domCtor  string // domain 常量前缀：Run / Job（domain.Run* / domain.Job*）
}

// machines 列出全部要生成的状态机。新增一台机器只需在此追加一行 + 写好它的 yaml。
var machines = []machine{
	{
		yamlFile: "states.yaml", goFile: "run_sm.gen.go", mdFile: "run_states.md",
		title: "Run", specRef: "§5.1",
		expPfx: "", unexpPfx: "run", domType: "RunState", domCtor: "Run",
	},
	{
		yamlFile: "job_states.yaml", goFile: "job_sm.gen.go", mdFile: "job_states.md",
		title: "Job", specRef: "§5.2",
		expPfx: "Job", unexpPfx: "job", domType: "JobState", domCtor: "Job",
	},
}

type doc struct {
	Version     int          `yaml:"version"`
	Initial     string       `yaml:"initial"`
	States      []string     `yaml:"states"`
	Terminal    []string     `yaml:"terminal"`
	Transitions []transition `yaml:"transitions"`
}

type transition struct {
	Event string   `yaml:"event"`
	From  flexFrom `yaml:"from"`
	To    string   `yaml:"to"`
}

// flexFrom 允许 from 写成单个状态或状态列表。
type flexFrom []string

func (f *flexFrom) UnmarshalYAML(value *yaml.Node) error {
	if value.Kind == yaml.ScalarNode {
		*f = []string{value.Value}
		return nil
	}
	var list []string
	if err := value.Decode(&list); err != nil {
		return err
	}
	*f = list
	return nil
}

func main() {
	for _, m := range machines {
		if err := gen(m); err != nil {
			fmt.Fprintf(os.Stderr, "gen(%s): %v\n", m.title, err)
			os.Exit(1)
		}
		fmt.Printf("gen: %s state machine ok\n", m.title)
	}
}

func gen(m machine) error {
	raw, err := os.ReadFile(m.yamlFile)
	if err != nil {
		return err
	}
	var d doc
	if err := yaml.Unmarshal(raw, &d); err != nil {
		return err
	}
	if err := validate(&d); err != nil {
		return err
	}
	if err := genGo(m, &d); err != nil {
		return err
	}
	return genMarkdown(m, &d)
}

// validate 穷举校验：状态/终态/迁移端点都必须在 states 里；终态无出边；无重复 (from,event)。
func validate(d *doc) error {
	stateSet := map[string]bool{}
	for _, s := range d.States {
		stateSet[s] = true
	}
	if !stateSet[d.Initial] {
		return fmt.Errorf("initial 状态 %q 不在 states 中", d.Initial)
	}
	termSet := map[string]bool{}
	for _, t := range d.Terminal {
		if !stateSet[t] {
			return fmt.Errorf("terminal 状态 %q 不在 states 中", t)
		}
		termSet[t] = true
	}
	seen := map[string]bool{} // from|event 去重
	for _, tr := range d.Transitions {
		if tr.Event == "" || tr.To == "" || len(tr.From) == 0 {
			return fmt.Errorf("迁移缺字段: %+v", tr)
		}
		if !stateSet[tr.To] {
			return fmt.Errorf("迁移 to %q 不在 states 中", tr.To)
		}
		for _, from := range tr.From {
			if !stateSet[from] {
				return fmt.Errorf("迁移 from %q 不在 states 中", from)
			}
			if termSet[from] {
				return fmt.Errorf("终态 %q 不能有出边（事件 %s）", from, tr.Event)
			}
			key := from + "|" + tr.Event
			if seen[key] {
				return fmt.Errorf("重复迁移: from=%s event=%s", from, tr.Event)
			}
			seen[key] = true
		}
	}
	return nil
}

func genGo(m machine, d *doc) error {
	// 事件按首次出现顺序收集，确定性输出。
	var events []string
	evSeen := map[string]bool{}
	for _, tr := range d.Transitions {
		if !evSeen[tr.Event] {
			evSeen[tr.Event] = true
			events = append(events, tr.Event)
		}
	}

	evType := m.expPfx + "Event"       // Event / JobEvent
	evConst := func(e string) string { // EventReady / JobEventReady
		return m.expPfx + "Event" + pascal(e)
	}
	domConst := func(s string) string { return "domain." + m.domCtor + pascal(s) }
	keyType := m.unexpPfx + "SmKey"        // runSmKey / jobSmKey
	termVar := m.unexpPfx + "TerminalSet"  // runTerminalSet / jobTerminalSet
	transVar := m.unexpPfx + "Transitions" // runTransitions / jobTransitions

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen.go from %s. DO NOT EDIT.\n\n", m.yamlFile)
	b.WriteString("package control\n\n")
	b.WriteString("import \"pentagent/internal/domain\"\n\n")

	fmt.Fprintf(&b, "// %s 是 %s 状态机的事件。\n", evType, m.title)
	fmt.Fprintf(&b, "type %s string\n\n", evType)
	b.WriteString("const (\n")
	for _, e := range events {
		fmt.Fprintf(&b, "\t%s %s = %q\n", evConst(e), evType, e)
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "// %sAllEvents 是全部事件（供穷举/属性测试）。\n", m.expPfx)
	fmt.Fprintf(&b, "var %sAllEvents = []%s{", m.expPfx, evType)
	for i, e := range events {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(evConst(e))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// %sAllStates 是全部状态。\n", m.expPfx)
	fmt.Fprintf(&b, "var %sAllStates = []domain.%s{", m.expPfx, m.domType)
	for i, s := range d.States {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(domConst(s))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "var %s = map[domain.%s]bool{\n", termVar, m.domType)
	for _, t := range d.Terminal {
		fmt.Fprintf(&b, "\t%s: true,\n", domConst(t))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "type %s struct {\n\tfrom domain.%s\n\tev   %s\n}\n\n", keyType, m.domType, evType)
	fmt.Fprintf(&b, "var %s = map[%s]domain.%s{\n", transVar, keyType, m.domType)
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "\t{%s, %s}: %s,\n", domConst(from), evConst(tr.Event), domConst(tr.To))
		}
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, `// %sNext 返回 (from, ev) 的下一状态。未登记的组合返回 (from, false) —— 显式拒绝，
// 不 panic、不卡原态。调用方据 ok=false 返回 ErrInvalid（见 *_controller.go）。
func %sNext(from domain.%s, ev %s) (domain.%s, bool) {
	to, ok := %s[%s{from, ev}]
	if !ok {
		return from, false
	}
	return to, true
}

// %sIsTerminal 报告状态是否为终态（无出边）。
func %sIsTerminal(s domain.%s) bool { return %s[s] }
`, m.expPfx, m.expPfx, m.domType, evType, m.domType, transVar, keyType,
		m.expPfx, m.expPfx, m.domType, termVar)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		_ = os.WriteFile(m.goFile, []byte(b.String()), 0o644)
		return fmt.Errorf("format: %w", err)
	}
	return os.WriteFile(m.goFile, formatted, 0o644)
}

func genMarkdown(m machine, d *doc) error {
	var b bytes.Buffer
	fmt.Fprintf(&b, "<!-- Generated by gen.go from %s. DO NOT EDIT. -->\n\n", m.yamlFile)
	fmt.Fprintf(&b, "# %s 状态机（%s）\n\n", m.title, m.specRef)
	fmt.Fprintf(&b, "初始状态：`%s`。终态：", d.Initial)
	for i, t := range d.Terminal {
		if i > 0 {
			b.WriteString("、")
		}
		fmt.Fprintf(&b, "`%s`", t)
	}
	b.WriteString("。\n\n## 状态图\n\n```mermaid\nstateDiagram-v2\n")
	fmt.Fprintf(&b, "    [*] --> %s\n", d.Initial)
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "    %s --> %s: %s\n", from, tr.To, tr.Event)
		}
	}
	b.WriteString("```\n\n## 迁移表\n\n| 当前状态 | 事件 | 下一状态 |\n|---|---|---|\n")
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", from, tr.Event, tr.To)
		}
	}
	b.WriteString("\n> 未在表中的 (状态, 事件) 组合一律被状态机显式拒绝（Next 返回 false），不产生迁移。\n")
	return os.WriteFile(m.mdFile, b.Bytes(), 0o644)
}

// --- 命名助手 ---

func titleWord(s string) string {
	if s == "" {
		return ""
	}
	return strings.ToUpper(s[:1]) + strings.ToLower(s[1:])
}

// pascal 把下划线分词转 PascalCase：WAITING_APPROVAL -> WaitingApproval、DRAFT -> Draft。
func pascal(s string) string {
	var b strings.Builder
	for _, p := range strings.Split(s, "_") {
		b.WriteString(titleWord(p))
	}
	return b.String()
}
