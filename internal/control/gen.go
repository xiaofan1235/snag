// gen.go —— 从 states.yaml 生成 Run 状态机（run_sm.gen.go）与状态图（run_states.md）。
// 用法：go generate ./internal/control/   （或在本目录 go run gen.go）
//
// 生成的 Next(from, event) 对任意 (状态,事件) 都有确定结果：已登记迁移返回 (to, true)，
// 未登记返回 (from, false) —— 显式拒绝、不 panic（§5.1 完整迁移表、Day 07）。
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"go.yaml.in/yaml/v3"
)

type doc struct {
	Version     int          `yaml:"version"`
	Initial     string       `yaml:"initial"`
	States      []string     `yaml:"states"`
	Terminal    []string     `yaml:"terminal"`
	Transitions []transition `yaml:"transitions"`
}

type transition struct {
	Event string   `yaml:"event"`
	From  flexFrom `yaml:"from"`
	To    string   `yaml:"to"`
}

// flexFrom 允许 from 写成单个状态或状态列表。
type flexFrom []string

func (f *flexFrom) UnmarshalYAML(value *yaml.Node) error {
	if value.Kind == yaml.ScalarNode {
		*f = []string{value.Value}
		return nil
	}
	var list []string
	if err := value.Decode(&list); err != nil {
		return err
	}
	*f = list
	return nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	fmt.Println("gen: run state machine ok")
}

func run() error {
	raw, err := os.ReadFile("states.yaml")
	if err != nil {
		return err
	}
	var d doc
	if err := yaml.Unmarshal(raw, &d); err != nil {
		return err
	}
	if err := validate(&d); err != nil {
		return err
	}
	if err := genGo(&d); err != nil {
		return err
	}
	return genMarkdown(&d)
}

// validate 穷举校验：状态/终态/迁移端点都必须在 states 里；终态无出边；无重复 (from,event)。
func validate(d *doc) error {
	stateSet := map[string]bool{}
	for _, s := range d.States {
		stateSet[s] = true
	}
	if !stateSet[d.Initial] {
		return fmt.Errorf("initial 状态 %q 不在 states 中", d.Initial)
	}
	termSet := map[string]bool{}
	for _, t := range d.Terminal {
		if !stateSet[t] {
			return fmt.Errorf("terminal 状态 %q 不在 states 中", t)
		}
		termSet[t] = true
	}
	seen := map[string]bool{} // from|event 去重
	for _, tr := range d.Transitions {
		if tr.Event == "" || tr.To == "" || len(tr.From) == 0 {
			return fmt.Errorf("迁移缺字段: %+v", tr)
		}
		if !stateSet[tr.To] {
			return fmt.Errorf("迁移 to %q 不在 states 中", tr.To)
		}
		for _, from := range tr.From {
			if !stateSet[from] {
				return fmt.Errorf("迁移 from %q 不在 states 中", from)
			}
			if termSet[from] {
				return fmt.Errorf("终态 %q 不能有出边（事件 %s）", from, tr.Event)
			}
			key := from + "|" + tr.Event
			if seen[key] {
				return fmt.Errorf("重复迁移: from=%s event=%s", from, tr.Event)
			}
			seen[key] = true
		}
	}
	return nil
}

func genGo(d *doc) error {
	// 事件按首次出现顺序收集，确定性输出。
	var events []string
	evSeen := map[string]bool{}
	for _, tr := range d.Transitions {
		if !evSeen[tr.Event] {
			evSeen[tr.Event] = true
			events = append(events, tr.Event)
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by gen.go from states.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package control\n\n")
	b.WriteString("import \"pentagent/internal/domain\"\n\n")

	b.WriteString("// Event 是 Run 状态机的事件。\n")
	b.WriteString("type Event string\n\n")
	b.WriteString("const (\n")
	for _, e := range events {
		fmt.Fprintf(&b, "\tEvent%s Event = %q\n", pascal(e), e)
	}
	b.WriteString(")\n\n")

	b.WriteString("// AllEvents 是全部事件（供穷举/属性测试）。\n")
	b.WriteString("var AllEvents = []Event{")
	for i, e := range events {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "Event%s", pascal(e))
	}
	b.WriteString("}\n\n")

	b.WriteString("// AllStates 是全部状态。\n")
	b.WriteString("var AllStates = []domain.RunState{")
	for i, s := range d.States {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(domainConst(s))
	}
	b.WriteString("}\n\n")

	b.WriteString("var terminalSet = map[domain.RunState]bool{\n")
	for _, t := range d.Terminal {
		fmt.Fprintf(&b, "\t%s: true,\n", domainConst(t))
	}
	b.WriteString("}\n\n")

	b.WriteString("type smKey struct {\n\tfrom domain.RunState\n\tev   Event\n}\n\n")
	b.WriteString("var runTransitions = map[smKey]domain.RunState{\n")
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "\t{%s, Event%s}: %s,\n", domainConst(from), pascal(tr.Event), domainConst(tr.To))
		}
	}
	b.WriteString("}\n\n")

	b.WriteString(`// Next 返回 (from, ev) 的下一状态。未登记的组合返回 (from, false) —— 显式拒绝，
// 不 panic、不卡原态。调用方据 ok=false 返回 ErrInvalid（见 run_controller.go）。
func Next(from domain.RunState, ev Event) (domain.RunState, bool) {
	to, ok := runTransitions[smKey{from, ev}]
	if !ok {
		return from, false
	}
	return to, true
}

// IsTerminal 报告状态是否为终态（无出边）。
func IsTerminal(s domain.RunState) bool { return terminalSet[s] }
`)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		_ = os.WriteFile("run_sm.gen.go", []byte(b.String()), 0o644)
		return fmt.Errorf("format: %w", err)
	}
	return os.WriteFile("run_sm.gen.go", formatted, 0o644)
}

func genMarkdown(d *doc) error {
	var b bytes.Buffer
	b.WriteString("<!-- Generated by gen.go from states.yaml. DO NOT EDIT. -->\n\n")
	b.WriteString("# Run 状态机（§5.1）\n\n")
	fmt.Fprintf(&b, "初始状态：`%s`。终态：", d.Initial)
	for i, t := range d.Terminal {
		if i > 0 {
			b.WriteString("、")
		}
		fmt.Fprintf(&b, "`%s`", t)
	}
	b.WriteString("。\n\n## 状态图\n\n```mermaid\nstateDiagram-v2\n")
	fmt.Fprintf(&b, "    [*] --> %s\n", d.Initial)
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "    %s --> %s: %s\n", from, tr.To, tr.Event)
		}
	}
	b.WriteString("```\n\n## 迁移表\n\n| 当前状态 | 事件 | 下一状态 |\n|---|---|---|\n")
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", from, tr.Event, tr.To)
		}
	}
	b.WriteString("\n> 未在表中的 (状态, 事件) 组合一律被状态机显式拒绝（Next 返回 false），不产生迁移。\n")
	return os.WriteFile("run_states.md", b.Bytes(), 0o644)
}

// --- 命名助手 ---

func titleWord(s string) string {
	if s == "" {
		return ""
	}
	return strings.ToUpper(s[:1]) + strings.ToLower(s[1:])
}

func pascal(ev string) string {
	var b strings.Builder
	for _, p := range strings.Split(ev, "_") {
		b.WriteString(titleWord(p))
	}
	return b.String()
}

// domainConst 把状态名映射到 domain 常量：DRAFT -> domain.RunDraft。
func domainConst(state string) string {
	return "domain.Run" + titleWord(state)
}
