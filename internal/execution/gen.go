//go:build ignore

// gen.go —— 从 action_states.yaml 生成 Action 状态机（action_sm.gen.go）与状态图（action_states.md）。
// 用法：go generate ./internal/execution/   （或在本目录 go run gen.go）
//
// 沿用 Day 07（internal/control/gen.go）同一套代码生成模式：完整迁移表 + 显式拒绝（Next 返回
// ok=false，不 panic、不卡原态）。此处为 execution 包的单机（Action）版本。
// 若将来 execution 再添状态机，可把此生成器与 control 的多机版抽成共享 internal/smgen。
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"go.yaml.in/yaml/v3"
)

const (
	yamlFile = "action_states.yaml"
	goFile   = "action_sm.gen.go"
	mdFile   = "action_states.md"
	title    = "Action"
	specRef  = "§5.3"
	expPfx   = "Action"      // 导出前缀：ActionEvent/ActionNext/...
	unexpPfx = "action"      // 非导出前缀：actionSmKey/actionTransitions/...
	domType  = "ActionState" // domain.ActionState
	domCtor  = "Action"      // domain.Action*
)

type doc struct {
	Version     int          `yaml:"version"`
	Initial     string       `yaml:"initial"`
	States      []string     `yaml:"states"`
	Terminal    []string     `yaml:"terminal"`
	Transitions []transition `yaml:"transitions"`
}

type transition struct {
	Event string   `yaml:"event"`
	From  flexFrom `yaml:"from"`
	To    string   `yaml:"to"`
}

// flexFrom 允许 from 写成单个状态或状态列表。
type flexFrom []string

func (f *flexFrom) UnmarshalYAML(value *yaml.Node) error {
	if value.Kind == yaml.ScalarNode {
		*f = []string{value.Value}
		return nil
	}
	var list []string
	if err := value.Decode(&list); err != nil {
		return err
	}
	*f = list
	return nil
}

func main() {
	raw, err := os.ReadFile(yamlFile)
	if err != nil {
		fail(err)
	}
	var d doc
	if err := yaml.Unmarshal(raw, &d); err != nil {
		fail(err)
	}
	if err := validate(&d); err != nil {
		fail(err)
	}
	if err := genGo(&d); err != nil {
		fail(err)
	}
	if err := genMarkdown(&d); err != nil {
		fail(err)
	}
	fmt.Printf("gen: %s state machine ok\n", title)
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "gen(%s): %v\n", title, err)
	os.Exit(1)
}

// validate 穷举校验：状态/终态/迁移端点都在 states 里；终态无出边；无重复 (from,event)。
func validate(d *doc) error {
	stateSet := map[string]bool{}
	for _, s := range d.States {
		stateSet[s] = true
	}
	if !stateSet[d.Initial] {
		return fmt.Errorf("initial 状态 %q 不在 states 中", d.Initial)
	}
	termSet := map[string]bool{}
	for _, t := range d.Terminal {
		if !stateSet[t] {
			return fmt.Errorf("terminal 状态 %q 不在 states 中", t)
		}
		termSet[t] = true
	}
	seen := map[string]bool{}
	for _, tr := range d.Transitions {
		if tr.Event == "" || tr.To == "" || len(tr.From) == 0 {
			return fmt.Errorf("迁移缺字段: %+v", tr)
		}
		if !stateSet[tr.To] {
			return fmt.Errorf("迁移 to %q 不在 states 中", tr.To)
		}
		for _, from := range tr.From {
			if !stateSet[from] {
				return fmt.Errorf("迁移 from %q 不在 states 中", from)
			}
			if termSet[from] {
				return fmt.Errorf("终态 %q 不能有出边（事件 %s）", from, tr.Event)
			}
			key := from + "|" + tr.Event
			if seen[key] {
				return fmt.Errorf("重复迁移: from=%s event=%s", from, tr.Event)
			}
			seen[key] = true
		}
	}
	return nil
}

func genGo(d *doc) error {
	var events []string
	evSeen := map[string]bool{}
	for _, tr := range d.Transitions {
		if !evSeen[tr.Event] {
			evSeen[tr.Event] = true
			events = append(events, tr.Event)
		}
	}
	evType := expPfx + "Event"
	evConst := func(e string) string { return expPfx + "Event" + pascal(e) }
	domConst := func(s string) string { return "domain." + domCtor + pascal(s) }
	keyType := unexpPfx + "SmKey"
	termVar := unexpPfx + "TerminalSet"
	transVar := unexpPfx + "Transitions"

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen.go from %s. DO NOT EDIT.\n\n", yamlFile)
	b.WriteString("package execution\n\n")
	b.WriteString("import \"pentagent/internal/domain\"\n\n")

	fmt.Fprintf(&b, "// %s 是 %s 状态机的事件。\n", evType, title)
	fmt.Fprintf(&b, "type %s string\n\n", evType)
	b.WriteString("const (\n")
	for _, e := range events {
		fmt.Fprintf(&b, "\t%s %s = %q\n", evConst(e), evType, e)
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "// %sAllEvents 是全部事件（供穷举/属性测试）。\n", expPfx)
	fmt.Fprintf(&b, "var %sAllEvents = []%s{", expPfx, evType)
	for i, e := range events {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(evConst(e))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// %sAllStates 是全部状态。\n", expPfx)
	fmt.Fprintf(&b, "var %sAllStates = []domain.%s{", expPfx, domType)
	for i, s := range d.States {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(domConst(s))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "var %s = map[domain.%s]bool{\n", termVar, domType)
	for _, t := range d.Terminal {
		fmt.Fprintf(&b, "\t%s: true,\n", domConst(t))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "type %s struct {\n\tfrom domain.%s\n\tev   %s\n}\n\n", keyType, domType, evType)
	fmt.Fprintf(&b, "var %s = map[%s]domain.%s{\n", transVar, keyType, domType)
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "\t{%s, %s}: %s,\n", domConst(from), evConst(tr.Event), domConst(tr.To))
		}
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, `// %sNext 返回 (from, ev) 的下一状态。未登记的组合返回 (from, false) —— 显式拒绝，
// 不 panic、不卡原态。调用方据 ok=false 返回 ErrInvalid。
func %sNext(from domain.%s, ev %s) (domain.%s, bool) {
	to, ok := %s[%s{from, ev}]
	if !ok {
		return from, false
	}
	return to, true
}

// %sIsTerminal 报告状态是否为终态（无出边）。
func %sIsTerminal(s domain.%s) bool { return %s[s] }
`, expPfx, expPfx, domType, evType, domType, transVar, keyType,
		expPfx, expPfx, domType, termVar)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		_ = os.WriteFile(goFile, []byte(b.String()), 0o644)
		return fmt.Errorf("format: %w", err)
	}
	return os.WriteFile(goFile, formatted, 0o644)
}

func genMarkdown(d *doc) error {
	var b bytes.Buffer
	fmt.Fprintf(&b, "<!-- Generated by gen.go from %s. DO NOT EDIT. -->\n\n", yamlFile)
	fmt.Fprintf(&b, "# %s 状态机（%s）\n\n", title, specRef)
	fmt.Fprintf(&b, "初始状态：`%s`。终态：", d.Initial)
	for i, t := range d.Terminal {
		if i > 0 {
			b.WriteString("、")
		}
		fmt.Fprintf(&b, "`%s`", t)
	}
	b.WriteString("。\n\n## 状态图\n\n```mermaid\nstateDiagram-v2\n")
	fmt.Fprintf(&b, "    [*] --> %s\n", d.Initial)
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "    %s --> %s: %s\n", from, tr.To, tr.Event)
		}
	}
	b.WriteString("```\n\n## 迁移表\n\n| 当前状态 | 事件 | 下一状态 |\n|---|---|---|\n")
	for _, tr := range d.Transitions {
		for _, from := range tr.From {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", from, tr.Event, tr.To)
		}
	}
	b.WriteString("\n> 未在表中的 (状态, 事件) 组合一律被状态机显式拒绝（Next 返回 false）。\n")
	return os.WriteFile(mdFile, b.Bytes(), 0o644)
}

func titleWord(s string) string {
	if s == "" {
		return ""
	}
	return strings.ToUpper(s[:1]) + strings.ToLower(s[1:])
}

// pascal：WAITING_APPROVAL -> WaitingApproval、PROPOSED -> Proposed。
func pascal(s string) string {
	var b strings.Builder
	for _, p := range strings.Split(s, "_") {
		b.WriteString(titleWord(p))
	}
	return b.String()
}
